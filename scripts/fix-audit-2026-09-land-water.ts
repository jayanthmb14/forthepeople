/** Prisma delegate name for a table ("CropPrice" → "cropPrice"). */
const delegateName = (table: string) => table[0].toLowerCase() + table.slice(1);

function same(current: unknown, planned: Value): boolean {
  if (current === null || current === undefined) return planned === null;
  if (planned === null) return false;
  if (typeof planned === "number") return Math.abs(Number(current) - planned) < 1e-6;
  if (typeof planned === "boolean") return current === planned;
  return String(current) === String(planned);
}

function show(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (v instanceof Date) return v.toISOString();
  if (typeof v === "string") return JSON.stringify(v.length > 70 ? v.slice(0, 67) + "…" : v);
  return String(v);
}

interface Planned {
  fix: Fix;
  data?: Record<string, Value>;
}

async function main() {
  // Guard: every row appears once, so two fixes never fight over it.
  const seen = new Set<string>();
  for (const f of FIXES) {
    const key = `${f.table}:${f.id}`;
    if (seen.has(key)) throw new Error(`Duplicate fix for ${key}`);
    seen.add(key);
    if ((f.op === "update" || f.op === "hide") && (!f.set || Object.keys(f.set).length === 0)) throw new Error(`No fields to set: ${key}`);
    if (f.op === "hide" && f.table !== "LocalAlert") throw new Error(`Only LocalAlert has an active flag: ${key}`);
  }

  const p = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL! }) });
  const plan: Planned[] = [];
  const counts: Record<string, { update: number; hide: number; delete: number; done: number; gone: number; drift: number }> = {};
  const tally = (t: string) => (counts[t] ??= { update: 0, hide: 0, delete: 0, done: 0, gone: 0, drift: 0 });

  try {
    console.log(`Land & water audit fixes (checked ${CHECKED}) — ${CONFIRM ? "APPLYING" : "DRY RUN"}`);
    let currentTable = "";
    for (const f of FIXES) {
      if (f.table !== currentTable) {
        currentTable = f.table;
        console.log(`\n══ ${f.table} ══`);
      }
      const rows = (await p.$queryRawUnsafe(`SELECT * FROM "${f.table}" WHERE id = $1`, f.id)) as Array<Record<string, unknown>>;
      const row = rows[0];
      const verb = f.op === "delete" ? "DELETE" : f.op === "hide" ? "HIDE (active → false)" : "UPDATE";
      console.log(`\n• ${verb} ${f.table} ${f.id} — finding #${f.finding}: ${f.label}`);
      console.log(`  why:    ${f.why}`);
      console.log(`  source: ${f.source}`);
      if (!row) {
        console.log("  → row not found (already deleted?) — skipped");
        tally(f.table).gone++;
        continue;
      }
      // Changed since the check? Compare every value we saw.
      const drifted = Object.entries(f.was).filter(([field, v]) => {
        if (!(field in row)) throw new Error(`${f.table}.${field} does not exist (fix ${f.id})`);
        // A field already holding the planned new value is not drift.
        if (f.set && field in f.set && same(row[field], f.set[field])) return false;
        return !same(row[field], v);
      });
      if (drifted.length > 0) {
        for (const [field, v] of drifted) console.log(`    ${field}: now ${show(row[field])}, was ${show(v)} on ${CHECKED} — CHANGED SINCE CHECK`);
        console.log("  → skipped; review by hand");
        tally(f.table).drift++;
        continue;
      }
      if (f.op === "delete") {
        for (const [field] of Object.entries(f.was)) console.log(`    ${field}: ${show(row[field])}`);
        console.log("  → delete whole row");
        plan.push({ fix: f });
        tally(f.table).delete++;
        continue;
      }
      const data: Record<string, Value> = {};
      for (const [field, planned] of Object.entries(f.set!)) {
        if (!(field in row)) throw new Error(`${f.table}.${field} does not exist (fix ${f.id})`);
        if (same(row[field], planned)) {
          console.log(`    ${field}: ${show(row[field])} (already ${show(planned)})`);
          continue;
        }
        console.log(`    ${field}: ${show(row[field])} → ${show(planned)}`);
        data[field] = planned;
      }
      if (Object.keys(data).length === 0) {
        console.log("  → already applied — skipped");
        tally(f.table).done++;
        continue;
      }
      plan.push({ fix: f, data });
      tally(f.table)[f.op === "hide" ? "hide" : "update"]++;
    }

    console.log("\n══ Summary ══");
    for (const [t, c] of Object.entries(counts)) {
      console.log(
        `${t.padEnd(12)} update ${String(c.update).padStart(2)}   hide ${String(c.hide).padStart(2)}   delete ${String(c.delete).padStart(2)}   already done ${String(c.done).padStart(2)}   not found ${String(c.gone).padStart(2)}   changed-since-check ${String(c.drift).padStart(2)}`,
      );
    }
    console.log(`Total changes to apply: ${plan.length}`);

    if (!CONFIRM) {
      console.log("\nDry run only. Re-run with --confirm to apply (one transaction).");
      return;
    }
    if (plan.length === 0) {
      console.log("Nothing to do.");
      return;
    }
    type Delegate = {
      update: (a: unknown) => Promise<unknown>;
      deleteMany: (a: unknown) => Promise<{ count: number }>;
    };
    const deletesByTable = new Map<string, string[]>();
    for (const { fix } of plan) {
      if (fix.op !== "delete") continue;
      deletesByTable.set(fix.table, [...(deletesByTable.get(fix.table) ?? []), fix.id]);
    }
    await p.$transaction(
      async (tx) => {
        const model = (table: string) => (tx as unknown as Record<string, Delegate>)[delegateName(table)];
        for (const { fix, data } of plan) {
          if (fix.op !== "delete") await model(fix.table).update({ where: { id: fix.id }, data });
        }
        for (const [table, ids] of deletesByTable) {
          const { count } = await model(table).deleteMany({ where: { id: { in: ids } } });
          if (count !== ids.length) throw new Error(`${table}: expected to delete ${ids.length} rows, deleted ${count} — rolled back`);
        }
      },
      { timeout: 120_000, maxWait: 30_000 },
    );
    console.log(`\nDone: applied ${plan.length} changes in one transaction.`);
    console.log("Clear the Redis caches (admin → Cache) so the crops, alerts and water pages pick this up at once.");
  } finally {
    await p.$disconnect();
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
