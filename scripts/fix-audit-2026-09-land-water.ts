type Table = "CropPrice" | "LocalAlert" | "DamReading";
type Value = string | number | boolean | null;

interface Fix {
  table: Table;
  id: string;
  /** update = new values; hide = LocalAlert.active → false; delete = remove the row. */
  op: "update" | "hide" | "delete";
  set?: Record<string, Value>;
  /** Values seen on the check day; any other current value = changed since check → skipped. */
  was: Record<string, Value>;
  /** Audit finding index (land-water.json) and a short label. */
  finding: number;
  label: string;
  why: string;
  source: string;
}

