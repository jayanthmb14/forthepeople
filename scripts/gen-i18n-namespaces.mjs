// Writes src/i18n/namespaces.ts from the per-page message files in
// src/dictionaries/en/*.json. Run automatically before dev and build, so
// adding a page's messages never needs a hand-edited list.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "src", "dictionaries", "en");
let names = [];
try {
  names = readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort();
} catch {
  names = [];
}
const out = `// GENERATED by scripts/gen-i18n-namespaces.mjs — do not edit.
// One entry per src/dictionaries/en/<name>.json (page-level messages).
export const PAGE_NAMESPACES: readonly string[] = ${JSON.stringify(names, null, 2)};
`;
writeFileSync(join(process.cwd(), "src", "i18n", "namespaces.ts"), out);
console.log(`[i18n] ${names.length} page namespace(s) indexed`);
