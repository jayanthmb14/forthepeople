// Cloudflare Worker entry: the OpenNext Next.js handler plus a scheduled
// handler that replaces Vercel Cron.
//
// wrangler.jsonc has ONE Cron Trigger, every 5 minutes. Each tick runs every
// cron in vercel.json (still the only schedule list) whose expression matches
// that minute, by calling the route in-process with the same
// `Authorization: Bearer <CRON_SECRET>` header Vercel Cron sent. Every
// vercel.json minute field is a multiple of 5 (tests/cron-schedule.test.ts).

// @ts-expect-error: generated by `opennextjs-cloudflare build`
import { default as handler } from "../.open-next/worker.js";
import vercel from "../vercel.json";
import { cronMatches } from "../src/lib/cron-match";

// @ts-expect-error: generated by `opennextjs-cloudflare build`
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "../.open-next/worker.js";

type Env = { CRON_SECRET?: string; CRON_ORIGIN?: string };
type Ctx = { waitUntil(p: Promise<unknown>): void };

async function runCron(path: string, env: Env, ctx: Ctx): Promise<void> {
  const origin = env.CRON_ORIGIN ?? "https://forthepeople.in";
  const started = Date.now();
  try {
    const res: Response = await handler.fetch(
      new Request(origin + path, {
        headers: { authorization: `Bearer ${env.CRON_SECRET ?? ""}`, "user-agent": "cloudflare-cron/1.0" },
      }),
      env,
      ctx,
    );
    console.log(`[cron] ${path} ${res.status} ${Date.now() - started}ms`);
  } catch (err) {
    console.error(`[cron] ${path} threw after ${Date.now() - started}ms`, err);
  }
}

export default {
  fetch: handler.fetch,

  async scheduled(controller: { scheduledTime: number }, env: Env, ctx: Ctx) {
    const at = new Date(controller.scheduledTime);
    for (const c of vercel.crons) {
      if (cronMatches(c.schedule, at)) ctx.waitUntil(runCron(c.path, env, ctx));
    }
  },
};
